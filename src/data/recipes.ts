export const RECIPES_BY_CATEGORY: Record<MealCategory, Recipe[]> = {
  breakfast: RECIPES.filter((r) => r.category === 'breakfast'),
  lunch: RECIPES.filter((r) => r.category === 'lunch'),
  dinner: RECIPES.filter((r) => r.category === 'dinner'),
  snack: RECIPES.filter((r) => r.category === 'snack'),
};

export const RECIPE_MAP: Record<string, Recipe> = Object.fromEntries(
  RECIPES.map((r) => [r.id, r]),
);

const CATEGORY_OFFSET: Record<MealCategory, number> = {
  breakfast: 0,
  lunch: 1,
  dinner: 2,
  snack: 3,
};

export function getDefaultRecipeForDay(day: number, category: MealCategory): Recipe {
  const list = RECIPES_BY_CATEGORY[category];
  const index = (day * 3 + CATEGORY_OFFSET[category]) % list.length;
  return list[index];
}
